#!/usr/bin/env bash
# One-shot CINECA environment setup - RUN ON A LOGIN NODE (needs internet).
#
# Guarantees:
#   - NOTHING lands in $HOME: venv, pip/HF/torch/triton caches, model
#     weights, datasets, runs all live under one base dir.
#   - Base dir = $1, or $FACT_BASE, or $WORK - falling back to $SCRATCH
#     when $WORK is missing or has < MIN_FREE_GB free. ($SCRATCH on
#     Leonardo is PURGED periodically - the script warns when it falls
#     back; caches/datasets there may need re-staging later.)
#   - Writes $BASE/fact_env.sh: source it in every shell and job (the
#     slurm/*.sbatch files do this via ${FACT_ENV}).
#   - Ends with scripts/verify_env.py: offline-readiness is PROVEN, not
#     assumed. Re-run that verifier inside a compute job too.
#
# Usage:
#   scripts/cineca_setup.sh [base_dir]
# Env knobs: MIN_FREE_GB (default 400), CUDA_WHEELS (default cu121),
#   WHISPER (e.g. large-v3 to also cache it), SKIP_DOWNLOADS=1,
#   BASELINES (default mimi,dac,vocos).
set -euo pipefail

MIN_FREE_GB=${MIN_FREE_GB:-400}
CUDA_WHEELS=${CUDA_WHEELS:-cu121}
BASELINES=${BASELINES:-mimi,dac,vocos}
REPO=$(cd "$(dirname "$0")/.." && pwd)

free_gb() { df -Pk "$1" 2>/dev/null | awk 'NR==2 {print int($4/1024/1024)}'; }

# ---------------------------------------------------------------- pick base
BASE="${1:-${FACT_BASE:-}}"
if [ -z "$BASE" ]; then
    if [ -n "${WORK:-}" ] && [ -d "$WORK" ] && [ "$(free_gb "$WORK")" -ge "$MIN_FREE_GB" ]; then
        BASE="$WORK/fact"
    elif [ -n "${SCRATCH:-}" ] && [ -d "$SCRATCH" ]; then
        BASE="$SCRATCH/fact"
        echo "WARNING: \$WORK missing or < ${MIN_FREE_GB}GB free -> using \$SCRATCH."
        echo "         Leonardo purges \$SCRATCH periodically: datasets/caches may vanish."
    else
        echo "ERROR: neither \$WORK nor \$SCRATCH usable; pass a base dir explicitly." >&2
        exit 1
    fi
fi
BASE=$(readlink -f "$BASE" 2>/dev/null || echo "$BASE")
case "$BASE" in
    "$HOME"|"$HOME"/*)
        echo "ERROR: base dir $BASE is inside \$HOME - refusing (tiny quota," >&2
        echo "       and compute nodes cannot refill it). Use \$WORK or \$SCRATCH." >&2
        exit 1;;
esac
case "$REPO" in
    "$HOME"|"$HOME"/*)
        echo "WARNING: this repo checkout is inside \$HOME ($REPO)."
        echo "         Re-clone under $BASE (code belongs on \$WORK too):"
        echo "         git clone <remote> $BASE/FaCT";;
esac
mkdir -p "$BASE"/{fact_cache,data,manifests,shards,runs}
echo "Base: $BASE ($(free_gb "$BASE") GB free)"

# ----------------------------------------------------------- write env file
ENV_FILE="$BASE/fact_env.sh"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/cineca_setup.sh - source in every shell and job.
export FACT_BASE="$BASE"
export FACT_CACHE="\$FACT_BASE/fact_cache"
export HF_HOME="\$FACT_CACHE/hf"                  # HF models + datasets cache
export XDG_CACHE_HOME="\$FACT_CACHE/xdg"          # pip, matplotlib, generic ~/.cache
export PIP_CACHE_DIR="\$FACT_CACHE/xdg/pip"
export TORCH_HOME="\$FACT_CACHE/torch"            # torch.hub
export TRITON_CACHE_DIR="\$FACT_CACHE/triton"
export TORCH_EXTENSIONS_DIR="\$FACT_CACHE/torch_extensions"
export NUMBA_CACHE_DIR="\$FACT_CACHE/numba"
if [ -f "\$FACT_BASE/fact-venv/bin/activate" ]; then
    source "\$FACT_BASE/fact-venv/bin/activate"
fi
EOF
echo "Wrote $ENV_FILE"
# shellcheck disable=SC1090
source "$ENV_FILE"
mkdir -p "$HF_HOME" "$XDG_CACHE_HOME" "$TORCH_HOME"

# ------------------------------------------------------------------- venv
if [ ! -f "$BASE/fact-venv/bin/activate" ]; then
    python -m venv "$BASE/fact-venv"
    source "$ENV_FILE"
fi
python -m pip install --upgrade pip --quiet
pip install --quiet torch torchaudio --index-url "https://download.pytorch.org/whl/$CUDA_WHEELS"
pip install --quiet -e "$REPO[audio,dev,eval]" vocos
echo "venv ready: $(python -V) @ $BASE/fact-venv"

# -------------------------------------------------------------- downloads
if [ "${SKIP_DOWNLOADS:-0}" != "1" ]; then
    python "$REPO/scripts/download_checkpoints.py" \
        --cache-dir "$FACT_CACHE" --baselines "$BASELINES" \
        ${WHISPER:+--whisper "$WHISPER"}
    if ! compgen -G "$BASE/data/eval/librispeech_test_clean/*.wav" > /dev/null; then
        python "$REPO/scripts/prepare_eval_set.py" \
            --out "$BASE/data/eval/librispeech_test_clean" -n 200
    fi
    DOWNLOAD_ONLY=1 bash "$REPO/scripts/smoke_test.sh" "$BASE/smoke"
fi

# ------------------------------------------------------------------ verify
python "$REPO/scripts/verify_env.py" --base "$BASE" \
    --out "$FACT_CACHE/verify_env.json"
echo
echo "Setup complete. In every future shell/job:  source $ENV_FILE"
echo "sbatch files pick it up via: FACT_ENV=$ENV_FILE sbatch ...  (or default \$WORK/fact/fact_env.sh)"
